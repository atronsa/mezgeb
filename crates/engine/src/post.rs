//! Atomic, idempotent posting (steps 1.09–1.11).
//!
//! One entry is one PostgreSQL transaction. Either every line, every total
//! update, the entry row and its idempotency record commit together, or
//! nothing does (ADR-0008, INV-4). If the process dies half way, PostgreSQL
//! rolls the transaction back.
//!
//! The same request (same client, key and fingerprint) has its effect once:
//! a repeat returns the original entry, a different request with the same
//! key is refused (INV-13).

use std::collections::{BTreeMap, BTreeSet};

use mezgeb_core::{
    AccountId, ClientId, EntryDraft, EntryId, Fingerprint, IdempotencyKey, LedgerError, LineDraft,
    PostedEntry, PostedLine, Side, reversal_fingerprint, validate,
};
use sqlx::{PgConnection, Row};
use uuid::Uuid;

use crate::concurrency::PostOptions;
use crate::rows::{
    ACCOUNT_COLUMNS, account_from_row, constraint_violation, db, entry_from_row, line_from_row,
    storage,
};

/// One request to post an entry.
#[derive(Debug, Clone)]
pub struct PostRequest {
    /// The new entry's ID, generated by the caller (the engine, later).
    pub entry_id: EntryId,
    /// The client posting it, and its idempotency key (INV-13).
    pub client_id: ClientId,
    pub idempotency_key: IdempotencyKey,
    pub draft: EntryDraft,
    /// Set for a reversal: the entry it mirrors (INV-14).
    pub reverses: Option<EntryId>,
}

/// Posts one entry atomically, with the default [`PostOptions`]
/// (ADR-0007):
///
/// 1. lock every account the entry touches with `FOR NO KEY UPDATE`, in
///    ascending ID order, so concurrent postings queue per account and can
///    never deadlock;
/// 2. validate the entry against those locked rows, with the same
///    `validate` as everywhere else, so the balance it checks cannot change
///    before commit;
/// 3. insert the entry;
/// 4. add the entry's net effect to each account's totals, one update per
///    account, and work out each line's totals after it;
/// 5. insert all lines in one statement;
/// 6. commit.
///
/// Before step 1, the idempotency key is claimed: if this client already
/// posted a request with this key, the original entry is returned (same
/// fingerprint) or the request is refused with `IdempotencyKeyReused`
/// (different fingerprint), and nothing is written.
///
/// A deadlock or serialization failure re-runs the whole transaction. The
/// database checks the result again at commit (docs/db-schema.md).
pub async fn post_entry(
    conn: &mut PgConnection,
    request: PostRequest,
) -> Result<PostedEntry, LedgerError> {
    post_entry_with(conn, request, &PostOptions::default()).await
}

/// [`post_entry`] with explicit concurrency options.
pub async fn post_entry_with(
    conn: &mut PgConnection,
    request: PostRequest,
    options: &PostOptions,
) -> Result<PostedEntry, LedgerError> {
    let mut attempt = 1;
    loop {
        let result = async {
            let mut tx = options.begin(conn).await?;
            if entry_exists(&mut tx, request.entry_id).await? {
                return Err(LedgerError::DuplicateEntry(request.entry_id));
            }
            let fingerprint = request.draft.fingerprint();
            if let Claim::Existing(original) = claim_key(&mut tx, &request, &fingerprint).await? {
                return Ok(original);
            }
            let posted = post_in_transaction(&mut tx, request.clone(), options).await?;
            tx.commit().await.map_err(db)?;
            options.after_commit()?;
            Ok(posted)
        }
        .await;
        match result {
            Err(error) if options.retry_after(&error, attempt).await => attempt += 1,
            other => return other,
        }
    }
}

/// Posts inside an open transaction, without committing, after the key has
/// been claimed. Used by [`post_entry`] and by reversals.
pub(crate) async fn post_in_transaction(
    conn: &mut PgConnection,
    request: PostRequest,
    options: &PostOptions,
) -> Result<PostedEntry, LedgerError> {
    let PostRequest {
        entry_id,
        client_id,
        idempotency_key,
        draft,
        reverses,
    } = request;

    // 1. Lock the accounts, in ascending ID order (ADR-0007).
    let ids: BTreeSet<AccountId> = draft.lines.iter().map(|l| l.account).collect();
    let uuids: Vec<Uuid> = ids.iter().map(|id| id.as_uuid()).collect();
    let rows = sqlx::query(sqlx::AssertSqlSafe(format!(
        "SELECT {ACCOUNT_COLUMNS} FROM accounts WHERE id = ANY($1) ORDER BY id{}",
        options.lock_clause()
    )))
    .bind(&uuids)
    .fetch_all(&mut *conn)
    .await
    .map_err(db)?;
    let mut accounts = BTreeMap::new();
    for row in &rows {
        let account = account_from_row(row)?;
        accounts.insert(account.id(), account);
    }

    // 2. Validate against the locked rows.
    let entry = validate(draft, &accounts).map_err(LedgerError::Posting)?;

    // 3. Insert the entry.
    let metadata = serde_json::to_string(entry.metadata()).map_err(storage)?;
    let inserted = sqlx::query(
        "INSERT INTO journal_entries
             (id, client_id, idempotency_key, reverses_entry_id, metadata, event_time)
         VALUES ($1, $2, $3, $4, $5::jsonb,
                 timestamptz 'epoch' + $6::bigint * interval '1 microsecond')
         RETURNING sequence",
    )
    .bind(entry_id.as_uuid())
    .bind(client_id.as_uuid())
    .bind(idempotency_key.as_str())
    .bind(reverses.map(|r| r.as_uuid()))
    .bind(metadata)
    .bind(entry.event_time().map(|t| t.as_micros()))
    .fetch_one(&mut *conn)
    .await
    .map_err(|e| entry_insert_error(e, entry_id, reverses))?;
    let sequence: i64 = inserted.try_get("sequence").map_err(db)?;

    // 4. Apply the entry's net effect to each account: one update per
    //    account, in ascending ID order. Updating line by line would fail
    //    for an entry that debits and credits the same account: the CHECK
    //    on accounts runs after every row update, and the first line alone
    //    could take the account below zero.
    let mut net: BTreeMap<AccountId, (i64, i64)> = BTreeMap::new();
    for line in entry.lines() {
        let (debits, credits) = net.entry(line.account()).or_insert((0, 0));
        // Cannot overflow: `validate` checked every account's new totals.
        match line.side() {
            Side::Debit => *debits += line.amount().amount(),
            Side::Credit => *credits += line.amount().amount(),
        }
    }
    let mut running: BTreeMap<AccountId, (i64, i64)> = BTreeMap::new();
    for (account, (debits, credits)) in &net {
        let totals = sqlx::query(
            "UPDATE accounts
                SET debits_total = debits_total + $2,
                    credits_total = credits_total + $3,
                    version = version + 1
              WHERE id = $1
          RETURNING debits_total, credits_total",
        )
        .bind(account.as_uuid())
        .bind(debits)
        .bind(credits)
        .fetch_one(&mut *conn)
        .await
        .map_err(db)?;
        let final_debits: i64 = totals.try_get("debits_total").map_err(db)?;
        let final_credits: i64 = totals.try_get("credits_total").map_err(db)?;
        // The totals before this entry, as stored by the database.
        running.insert(*account, (final_debits - debits, final_credits - credits));
    }

    // Each line's totals after it, walking the lines in order from the
    // stored starting totals (ADR-0012).
    let mut lines = Vec::with_capacity(entry.lines().len());
    for line in entry.lines() {
        let totals = running
            .get_mut(&line.account())
            .ok_or_else(|| storage("line account was not updated"))?;
        match line.side() {
            Side::Debit => totals.0 += line.amount().amount(),
            Side::Credit => totals.1 += line.amount().amount(),
        }
        lines.push(PostedLine::new(
            line.account(),
            line.side(),
            line.amount(),
            totals.0,
            totals.1,
        ));
    }

    // 5. Insert every line in one statement.
    insert_lines(conn, entry_id, &lines).await?;

    let sequence = u64::try_from(sequence).map_err(storage)?;
    Ok(PostedEntry::new(
        entry_id,
        sequence,
        lines,
        reverses,
        entry.metadata().clone(),
        entry.event_time(),
    ))
}

async fn insert_lines(
    conn: &mut PgConnection,
    entry_id: EntryId,
    lines: &[PostedLine],
) -> Result<(), LedgerError> {
    let count = lines.len();
    let line_numbers: Vec<i16> = (0..count)
        .map(|n| i16::try_from(n).map_err(storage))
        .collect::<Result<_, _>>()?;
    sqlx::query(
        "INSERT INTO journal_lines
             (entry_id, line_no, account_id, side, amount, currency, debits_after, credits_after)
         SELECT * FROM UNNEST($1::uuid[], $2::int2[], $3::uuid[], $4::text[], $5::int8[],
                              $6::text[], $7::int8[], $8::int8[])",
    )
    .bind(vec![entry_id.as_uuid(); count])
    .bind(line_numbers)
    .bind(
        lines
            .iter()
            .map(|l| l.account().as_uuid())
            .collect::<Vec<_>>(),
    )
    .bind(lines.iter().map(|l| l.side().as_str()).collect::<Vec<_>>())
    .bind(
        lines
            .iter()
            .map(|l| l.amount().amount())
            .collect::<Vec<_>>(),
    )
    .bind(
        lines
            .iter()
            .map(|l| l.amount().currency().code())
            .collect::<Vec<_>>(),
    )
    .bind(
        lines
            .iter()
            .map(PostedLine::debits_after)
            .collect::<Vec<_>>(),
    )
    .bind(
        lines
            .iter()
            .map(PostedLine::credits_after)
            .collect::<Vec<_>>(),
    )
    .execute(&mut *conn)
    .await
    .map_err(db)?;
    Ok(())
}

async fn entry_exists(conn: &mut PgConnection, id: EntryId) -> Result<bool, LedgerError> {
    sqlx::query_scalar("SELECT EXISTS (SELECT 1 FROM journal_entries WHERE id = $1)")
        .bind(id.as_uuid())
        .fetch_one(conn)
        .await
        .map_err(db)
}

/// Maps a failed entry insert. Two concurrent reversals of one entry both
/// pass the checks before inserting; the UNIQUE constraint stops the second.
fn entry_insert_error(error: sqlx::Error, id: EntryId, reverses: Option<EntryId>) -> LedgerError {
    match (constraint_violation(&error), reverses) {
        (Some((code, constraint)), Some(original))
            if code == "23505" && constraint == "journal_entries_reverses_entry_id_key" =>
        {
            LedgerError::AlreadyReversed(original)
        }
        (Some((code, constraint)), _)
            if code == "23505" && constraint == "journal_entries_pkey" =>
        {
            LedgerError::DuplicateEntry(id)
        }
        (Some((code, constraint)), _)
            if code == "23505" && constraint == "journal_entries_idempotency_unique" =>
        {
            LedgerError::IdempotencyKeyReused
        }
        _ => db(error),
    }
}

/// Posts the exact mirror of `original` as `request.entry_id` (INV-14).
/// `request.draft` and `request.reverses` are ignored and built from the
/// original.
pub async fn reverse_entry(
    conn: &mut PgConnection,
    original: EntryId,
    request: PostRequest,
) -> Result<PostedEntry, LedgerError> {
    reverse_entry_with(conn, original, request, &PostOptions::default()).await
}

/// [`reverse_entry`] with explicit concurrency options.
pub async fn reverse_entry_with(
    conn: &mut PgConnection,
    original: EntryId,
    request: PostRequest,
    options: &PostOptions,
) -> Result<PostedEntry, LedgerError> {
    let mut attempt = 1;
    loop {
        let result = reverse_once(conn, original, request.clone(), options).await;
        match result {
            Err(error) if options.retry_after(&error, attempt).await => attempt += 1,
            other => return other,
        }
    }
}

async fn reverse_once(
    conn: &mut PgConnection,
    original: EntryId,
    request: PostRequest,
    options: &PostOptions,
) -> Result<PostedEntry, LedgerError> {
    let mut tx = options.begin(conn).await?;
    if entry_exists(&mut tx, request.entry_id).await? {
        return Err(LedgerError::DuplicateEntry(request.entry_id));
    }
    let fingerprint = reversal_fingerprint(original);
    if let Claim::Existing(reversal) = claim_key(&mut tx, &request, &fingerprint).await? {
        return Ok(reversal);
    }
    let target: Option<Option<Uuid>> =
        sqlx::query_scalar("SELECT reverses_entry_id FROM journal_entries WHERE id = $1")
            .bind(original.as_uuid())
            .fetch_optional(&mut *tx)
            .await
            .map_err(db)?;
    match target {
        None => return Err(LedgerError::EntryNotFound(original)),
        Some(Some(_)) => return Err(LedgerError::CannotReverseReversal(original)),
        Some(None) => {}
    }
    let reversed: bool = sqlx::query_scalar(
        "SELECT EXISTS (SELECT 1 FROM journal_entries WHERE reverses_entry_id = $1)",
    )
    .bind(original.as_uuid())
    .fetch_one(&mut *tx)
    .await
    .map_err(db)?;
    if reversed {
        return Err(LedgerError::AlreadyReversed(original));
    }

    let rows = sqlx::query(
        "SELECT account_id, side, amount, currency, debits_after, credits_after
           FROM journal_lines WHERE entry_id = $1 ORDER BY line_no",
    )
    .bind(original.as_uuid())
    .fetch_all(&mut *tx)
    .await
    .map_err(db)?;
    let mut mirror = EntryDraft {
        // The original passed the duplicate rule or allowed duplicates.
        allow_duplicate_lines: true,
        ..EntryDraft::default()
    };
    for row in &rows {
        let line = crate::rows::line_from_row(row)?;
        mirror.lines.push(LineDraft {
            account: line.account(),
            side: match line.side() {
                Side::Debit => Side::Credit,
                Side::Credit => Side::Debit,
            },
            amount: line.amount().money(),
        });
    }

    let posted = post_in_transaction(
        &mut tx,
        PostRequest {
            draft: mirror,
            reverses: Some(original),
            ..request
        },
        options,
    )
    .await?;
    tx.commit().await.map_err(db)?;
    Ok(posted)
}

/// The result of claiming an idempotency key.
enum Claim {
    /// The key was free and is now held by this transaction.
    New,
    /// The key was already used for the same request: its entry.
    Existing(PostedEntry),
}

/// Claims `request`'s idempotency key for its entry, before any account is
/// locked. If another transaction holds the same key and has not finished,
/// PostgreSQL makes this one wait on the primary key until it commits (the
/// key is then taken) or rolls back (the key is free again).
async fn claim_key(
    conn: &mut PgConnection,
    request: &PostRequest,
    fingerprint: &Fingerprint,
) -> Result<Claim, LedgerError> {
    let claimed = sqlx::query(
        "INSERT INTO idempotency_records (client_id, idempotency_key, request_hash, entry_id)
         VALUES ($1, $2, $3, $4)
         ON CONFLICT (client_id, idempotency_key) DO NOTHING",
    )
    .bind(request.client_id.as_uuid())
    .bind(request.idempotency_key.as_str())
    .bind(fingerprint.as_slice())
    .bind(request.entry_id.as_uuid())
    .execute(&mut *conn)
    .await
    .map_err(db)?;
    if claimed.rows_affected() == 1 {
        return Ok(Claim::New);
    }
    let (hash, entry): (Vec<u8>, Uuid) = sqlx::query_as(
        "SELECT request_hash, entry_id FROM idempotency_records
          WHERE client_id = $1 AND idempotency_key = $2",
    )
    .bind(request.client_id.as_uuid())
    .bind(request.idempotency_key.as_str())
    .fetch_one(&mut *conn)
    .await
    .map_err(db)?;
    if hash.as_slice() != fingerprint.as_slice() {
        return Err(LedgerError::IdempotencyKeyReused);
    }
    let id = crate::rows::entry_id(entry)?;
    load_entry(conn, id)
        .await?
        .map(Claim::Existing)
        .ok_or_else(|| storage("an idempotency record points to a missing entry"))
}

/// Reads one posted entry with its lines.
pub(crate) async fn load_entry(
    conn: &mut PgConnection,
    id: EntryId,
) -> Result<Option<PostedEntry>, LedgerError> {
    let Some(row) = sqlx::query(
        "SELECT id, sequence, reverses_entry_id, metadata::text AS metadata,
                (extract(epoch FROM event_time) * 1000000)::bigint AS event_time_micros
           FROM journal_entries WHERE id = $1",
    )
    .bind(id.as_uuid())
    .fetch_optional(&mut *conn)
    .await
    .map_err(db)?
    else {
        return Ok(None);
    };
    let line_rows = sqlx::query(
        "SELECT account_id, side, amount, currency, debits_after, credits_after
           FROM journal_lines WHERE entry_id = $1 ORDER BY line_no",
    )
    .bind(id.as_uuid())
    .fetch_all(&mut *conn)
    .await
    .map_err(db)?;
    let lines = line_rows
        .iter()
        .map(line_from_row)
        .collect::<Result<Vec<_>, _>>()?;
    entry_from_row(&row, lines).map(Some)
}

/// The entry a client posted with this idempotency key, if any. A client
/// that lost a response uses it to learn the outcome without posting again
/// (ADR-0008).
pub async fn lookup_by_idempotency_key(
    conn: &mut PgConnection,
    client: ClientId,
    key: &IdempotencyKey,
) -> Result<Option<PostedEntry>, LedgerError> {
    let entry: Option<Uuid> = sqlx::query_scalar(
        "SELECT entry_id FROM idempotency_records WHERE client_id = $1 AND idempotency_key = $2",
    )
    .bind(client.as_uuid())
    .bind(key.as_str())
    .fetch_optional(&mut *conn)
    .await
    .map_err(db)?;
    match entry {
        Some(entry) => load_entry(conn, crate::rows::entry_id(entry)?).await,
        None => Ok(None),
    }
}
